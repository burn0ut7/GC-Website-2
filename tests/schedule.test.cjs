const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({ Intl, Date });
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, '../dist/schedule.js'), 'utf8'), context);
const sessions = iso => context.upcomingSessions(new Date(iso)).map(date => date.toISOString());
assert.equal(sessions('2026-07-01T00:00:00Z')[0], '2026-07-04T19:00:00.000Z');
assert.equal(sessions('2026-11-02T00:00:00Z')[0], '2026-11-07T20:00:00.000Z');
const autumn = sessions('2026-10-23T00:00:00Z');
assert.equal(autumn[0], '2026-10-24T19:00:00.000Z');
assert.equal(autumn[1], '2026-10-25T20:00:00.000Z');
assert.equal(context.scheduleParts(new Date(autumn[0]), 'America/New_York').hour, 15);
assert.equal(context.scheduleParts(new Date(autumn[1]), 'America/New_York').hour, 16);
assert.equal(context.scheduleParts(new Date(sessions('2026-11-02T00:00:00Z')[0]), 'America/New_York').hour, 15);
assert.equal(context.scheduleParts(new Date(sessions('2026-03-13T00:00:00Z')[0]), 'America/New_York').hour, 16);
const now = new Date('2026-11-02T00:00:00Z');
assert.equal(context.sessionDisplay(now, 'Asia/Tokyo').days, 'Sunday & Monday');
assert.match(context.sessionDisplay(now, 'America/New_York').time, /EST|GMT-5/);
assert.doesNotMatch(context.sessionDisplay(now, 'America/New_York').time, /local time/);
assert.match(context.sessionDisplay(now, null).time, /UTC/);
assert.match(context.sessionDisplay(now, 'invalid/timezone').time, /UTC/);
assert.match(context.sessionDisplay(now, 'UTC', '24h').time, /20:00/);
assert.match(context.sessionDisplay(now, 'UTC', '12h').time, /8:00\s*PM/i);
assert.equal(context.sessionDisplay(new Date('2026-10-23T00:00:00Z'), 'America/New_York').days, 'Upcoming sessions');
assert.equal(sessions('2026-11-07T20:00:01Z')[0], '2026-11-08T20:00:00.000Z');
console.log('PASS: European DST, Eastern transition gap, local date rollover, UTC fallback and elapsed sessions');

assert.equal(context.sessionDisplay(now, 'UTC').nextIso, '2026-11-07T20:00:00.000Z');
assert.match(context.sessionDisplay(now, 'America/New_York').nextDate, /November 7, 2026/);
assert.match(context.sessionDisplay(now, 'America/New_York').nextDate, /EST|GMT-5/);
assert.match(context.sessionDisplay(now, 'Asia/Tokyo').nextDate, /November 8, 2026/);
assert.equal(context.sessionCountdown('2026-11-14T20:00:00Z', new Date('2026-11-13T18:57:56Z')), '1d 1h 2m 4s');
assert.equal(context.sessionCountdown('2026-11-14T20:00:00Z', new Date('2026-11-14T20:00:00Z')), '0d 0h 0m 0s');
assert.equal(context.sessionCountdown('2026-11-14T20:00:00Z', new Date('2026-11-14T20:00:01Z')), '0d 0h 0m 0s');
console.log('PASS: exact next-session date, timezone date rollover and countdown boundaries');
